import logging

from bs4 import Tag, ResultSet, BeautifulSoup

from lihzahrd._generate.class_name_factory import ClassNameFactory

log = logging.getLogger(__name__)


class TilesGenerator:
    """
    Class that reads a ``tiles.xml`` file `from TerraMap`_ and outputs Python code using :mod:`lihzahrd` structures to represent it.

    .. _from TerraMap: https://github.com/TerraMap/windows/blob/master/Data/tiles.xml
    """

    def __init__(self, soup: BeautifulSoup):
        """
        Create a new instance of the generator, given an XML tiles document processed with :mod:`BeautifulSoup4` (:mod:`lxml`).

        :param soup: The processed XML tiles document.
        """
        self.factory: ClassNameFactory = ClassNameFactory()
        tiles = self._tiles_element(soup)
        self.tile: ResultSet[Tag] = self._tile_elements(tiles)
        self.wall: ResultSet[Tag] = self._wall_elements(tiles)
        self.prefix: ResultSet[Tag] = self._prefix_elements(tiles)
        self.item: ResultSet[Tag] = self._item_elements(tiles)
        self.global_: ResultSet[Tag] = self._global_elements(tiles)
        self.npc: ResultSet[Tag] = self._npc_elements(tiles)

    @classmethod
    def _tiles_element(cls, soup: BeautifulSoup) -> Tag:
        """
        :param soup: The processed XML tiles document to search for the tag in.
        :return: The ``<tiles>`` element of the ``soup``.
        :raise ValueError: If no ``<tiles>`` element exists in the document.
        """
        log.debug("Finding <tiles> element...")
        if result := soup.find("tiles", recursive=False):
            return result
        raise ValueError("Could not find a `tiles` element.")

    @classmethod
    def _tile_elements(cls, tiles: Tag) -> ResultSet[Tag]:
        """
        :param tiles: The ``<tiles>`` element returned by :meth:`._tiles_element`.
        :return: All the ``<tile>`` elements that are direct children of the :meth:`._tiles_element`.
        """
        log.debug("Finding <tile> elements...")
        return tiles.find_all("tile", recursive=False)

    @classmethod
    def _var_elements(cls, element: Tag) -> ResultSet[Tag]:
        """
        :param element: A single element, returned by either :meth:`._tile_elements` or :meth:`._var_elements` itself.
        :return: All the ``<var>`` elements that are direct children of ``tile``.
        """
        log.debug("Finding <var> elements...")
        return element.find_all("var", recursive=False)

    @classmethod
    def _wall_elements(cls, tiles: Tag) -> ResultSet[Tag]:
        """
        :param tiles: The ``<tiles>`` element returned by :meth:`._tiles_element`.
        :return: All the ``<wall>`` elements that are direct children of ``tiles``.
        """
        log.debug("Finding <wall> elements...")
        return tiles.find_all("wall", recursive=False)

    @classmethod
    def _prefix_elements(cls, tiles: Tag) -> ResultSet[Tag]:
        """
        :param tiles: The ``<tiles>`` element returned by :meth:`._tiles_element`.
        :return: All the ``<prefix>`` elements that are direct children of ``tiles``.
        """
        log.debug("Finding <prefix> elements...")
        return tiles.find_all("prefix", recursive=False)

    @classmethod
    def _item_elements(cls, tiles: Tag) -> ResultSet[Tag]:
        """
        :param tiles: The ``<tiles>`` element returned by :meth:`._tiles_element`.
        :return: All the ``<item>`` elements that are direct children of ``tiles``.
        """
        log.debug("Finding <item> elements...")
        return tiles.find_all("item", recursive=False)

    @classmethod
    def _global_elements(cls, tiles: Tag) -> ResultSet[Tag]:
        """
        :param tiles: The ``<tiles>`` element returned by :meth:`._tiles_element`.
        :return: All the ``<global>`` elements that are direct children of ``tiles``.
        """
        log.debug("Finding <global> elements...")
        return tiles.find_all("global", recursive=False)

    @classmethod
    def _npc_elements(cls, tiles: Tag) -> ResultSet[Tag]:
        """
        :param tiles: The ``<tiles>`` element returned by :meth:`._tiles_element`.
        :return: All the ``<Npc>`` elements that are direct children of ``tiles``.

        .. note::

            ``<Npc>`` has an uppercase N.
        """
        log.debug("Finding <Npc> elements...")
        return tiles.find_all("Npc", recursive=False)

    @staticmethod
    def _generate_module_docstring() -> str:
        log.debug("Generating module docstring...")
        return (
            "# language=rst\n"
            '"""\n'
            ".. note::\n"
            "\n"
            "    This module was partially generated by :class:`lihzahrd._generate.terraria.tiles_generator.TilesGenerator`.\n"
            "\n"
            '"""\n'
            "\n"
        )

    @staticmethod
    def _generate_dunder_all(names) -> str:
        result = []

        result.append("__all__ = (")

        for name in names:
            result.append(f"    {name!r},")

        result.append(")")

        return "\n".join(result) + "\n"

    def generate_blocks(self) -> str:
        """
        Generate the new contents of :mod:`lihzahrd.terraria.data.classmembers.blocks`.

        :returns: The contents, as a :class:`str`.
        """
        log.debug("Generating blocks...")

        result = [
            self._generate_module_docstring(),
            self._generate_blocks_imports(),
        ]

        names = []

        for tile in self.tile:
            name, code = self._generate_block(tile=tile)
            result.append(code)
            names.append(name)

        result.append(self._generate_dunder_all(names))

        return "".join(result)

    @staticmethod
    def _generate_blocks_imports() -> str:
        log.debug("Generating block imports...")
        return (
            "from lihzahrd.terraria.data.frameimportant_variant import FrameImportantVariant\n"
            "from lihzahrd.terraria.data.classmembers.block_base import BlockBase\n"
            "from lihzahrd.terraria.data.classenums.block_enum import BlockEnum\n"
            "from lihzahrd.terraria.utils.structures.color import ColorRGB\n"
            "\n"
            "\n"
        )

    def _generate_block(self, tile: Tag) -> tuple[str, str]:
        log.debug("Generating block...")

        tile_id = tile["num"]
        tile_id = int(tile_id)
        log.debug("Block id is: %r", tile_id)

        tile_name = tile["name"]
        tile_name = str(tile_name)
        log.debug("Block name is: %r", tile_name)

        class_name = self.factory(tile_name, "Block")
        log.debug("Class name is: %r", class_name)

        attributes = self._generate_block_attributes(tile)
        variants = self._generate_block_variants(tile)

        return (
            class_name,
            (
                f"class {class_name!s}(BlockBase, metaclass=BlockEnum, ID={tile_id!r}, NAME={tile_name!r}):\n"
                f"{attributes}\n"
                f"    FRAMEIMPORTANT_VARIANTS = (\n"
                f"{variants}\n"
                f"    )\n"
                f"\n"
                f"\n"
            ),
        )

    @staticmethod
    def _generate_block_attributes(block: Tag) -> str:
        log.debug("Generating block attributes...")

        result = []

        if value := block.get("color"):
            result.append(f"    COLOR = ColorRGB(h={value!r})")
        del value

        if value := block.get("solid"):
            value = bool(int(value))
            result.append(f"    SOLID = {value!r}")
        del value

        if value := block.get("blend"):
            value = bool(int(value))
            result.append(f"    BLEND = {value!r}")
        del value

        if value := block.get("merge"):
            value = bool(int(value))
            result.append(f"    MERGE = {value!r}")
        del value

        if value := block.get("letLight"):
            value = bool(int(value))
            result.append(f"    TRANSPARENT = {value!r}")
        del value

        if value := block.get("isStone"):
            value = bool(int(value))
            result.append(f"    IS_STONE = {value!r}")
        del value

        if value := block.get("isGrass"):
            value = bool(int(value))
            result.append(f"    IS_GRASS = {value!r}")
        del value

        value_r = block.get("lightr")
        value_g = block.get("lightg")
        value_b = block.get("lightb")
        if value_r and value_g and value_b:
            value_r = float(value_r)
            value_g = float(value_g)
            value_b = float(value_b)
            result.append(f"    EMIT_LIGHT_COLOR = ColorRGB(r={value_r!r}, g={value_g!r}, b={value_b!r})")
        del value_r
        del value_g
        del value_b

        if len(result) == 0:
            result.append("    pass")

        return "\n".join(result)

    def _generate_block_variants(self, block: Tag) -> str:
        log.debug("Generating block variants...")

        result = []

        for var in self._var_elements(block):
            result.append("        FrameImportantVariant(")

            if value := var.get("u"):
                value = int(value)
                result.append(f"            eq_u={value!r},")
            del value

            if value := var.get("v"):
                value = int(value)
                result.append(f"            eq_v={value!r},")
            del value

            if value := var.get("minu"):
                value = int(value)
                result.append(f"            min_u={value!r},")
            del value

            if value := var.get("minv"):
                value = int(value)
                result.append(f"            min_v={value!r},")
            del value

            if value := var.get("maxu"):
                value = int(value)
                result.append(f"            max_u={value!r},")
            del value

            if value := var.get("maxv"):
                value = int(value)
                result.append(f"            max_v={value!r},")
            del value

            if value := var.get("name"):
                result.append(f"            name={value!r},")
            del value

            if value := var.get("color"):
                result.append(f"            color=ColorRGB(h={value!r}),")
            del value

            if value := var.get("solid"):
                value = bool(int(value))
                result.append(f"            solid={value!r},")
            del value

            if value := var.get("blend"):
                value = bool(int(value))
                result.append(f"            blend={value!r},")
            del value

            if value := var.get("merge"):
                value = bool(int(value))
                result.append(f"            merge={value!r},")
            del value

            if value := var.get("letLight"):
                value = bool(int(value))
                result.append(f"            transparent={value!r},")
            del value

            if value := var.get("isStone"):
                value = bool(int(value))
                result.append(f"            is_stone={value!r},")
            del value

            if value := var.get("isGrass"):
                value = bool(int(value))
                result.append(f"            is_grass={value!r},")
            del value

            result.append("        ),")

        return "\n".join(result)

    def generate_items(self) -> str:
        """
        Generate the new contents of :mod:`lihzahrd.terraria.data.classmembers.items`.

        :returns: The contents, as a :class:`str`.
        """
