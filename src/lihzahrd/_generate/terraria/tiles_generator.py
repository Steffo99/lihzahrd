        result = []

        if value := wall.get("color"):
            result.append(f"    COLOR = ColorRGB(h={value!r})")
        del value

        if value := wall.get("blend"):
            value = int(value)
            result.append(f"    BLEND = {value!r}")
        del value

        if len(result) == 0:
            result.append(f"    pass")

        return "\n".join(result)


